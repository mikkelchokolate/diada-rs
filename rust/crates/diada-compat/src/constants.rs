//! Original Extended constant encodings. Decimal literals and modern PI
//! substitutions do not define the DIADA compatibility calculations.
use crate::Extended80;

pub const PI: Extended80 =
    Extended80::from_le_bytes([0x35, 0xc2, 0x68, 0x21, 0xa2, 0xda, 0x0f, 0xc9, 0x00, 0x40]);
pub const HALF_PI_ROUNDED: Extended80 =
    Extended80::from_le_bytes([0x14, 0xcd, 0x03, 0x58, 0xe4, 0xd7, 0x0f, 0xc9, 0xff, 0x3f]);
pub const DEG_TO_RAD: Extended80 =
    Extended80::from_le_bytes([0x84, 0x68, 0x4a, 0x3e, 0xb8, 0x33, 0xfa, 0x8e, 0xf9, 0x3f]);
pub const RAD_TO_DEG: Extended80 =
    Extended80::from_le_bytes([0x54, 0x57, 0x3e, 0xcb, 0xf3, 0xe0, 0x2e, 0xe5, 0x04, 0x40]);
pub const TAU_ROUNDED: Extended80 =
    Extended80::from_le_bytes([0xd2, 0xe3, 0xf7, 0x36, 0xfd, 0xd9, 0x0f, 0xc9, 0x01, 0x40]);
pub const EPSILON: Extended80 =
    Extended80::from_le_bytes([0xb6, 0x69, 0x6c, 0xaf, 0x05, 0xbd, 0x37, 0x86, 0xeb, 0x3f]);
pub const GRAVITY: Extended80 =
    Extended80::from_le_bytes([0xc3, 0xf5, 0x28, 0x5c, 0x8f, 0xc2, 0xf5, 0x9c, 0x02, 0x40]);

pub(crate) const QUARTER_PI: Extended80 =
    Extended80::from_le_bytes([0x35, 0xc2, 0x68, 0x21, 0xa2, 0xda, 0x0f, 0xc9, 0xfe, 0x3f]);
pub(crate) const HALF_PI: Extended80 =
    Extended80::from_le_bytes([0x35, 0xc2, 0x68, 0x21, 0xa2, 0xda, 0x0f, 0xc9, 0xff, 0x3f]);
